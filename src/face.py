FEATURE_NAMES = ("perclos", "brate", "nod")


def _d(P, a, b):
    return float(np.linalg.norm(P[a] - P[b]))


def points(lm, w, h):
    """mediapipe 归一化关键点 -> 像素坐标字典（只取 NEED 里用得到的）。"""
    return {j: np.array([lm[j].x * w, lm[j].y * h]) for j in NEED}


def ear_of(P):
    """EAR = 上下眼睑距离均值 / 内外眼角距离，双眼取平均。尺度无关。"""
    out = []
    for e in ("l", "r"):
        c1, c2 = EYE[e]["corner"]
        w = _d(P, c1, c2)
        if w < 1e-6:
            continue
        v = float(np.mean([_d(P, a, b) for a, b in EYE[e]["pairs"]]))
        out.append(v / w)
    return float(np.mean(out)) if out else np.nan


def mar_of(P):
    """MAR = (内唇距 + 外唇距)/2 / 嘴角距。"""
    c1, c2 = MOUTH["corner"]
    w = _d(P, c1, c2)
    if w < 1e-6:
        return np.nan
    return float(np.mean([_d(P, *MOUTH["inner"]), _d(P, *MOUTH["outer"])])) / w


def euler_of(M):
    """4x4 面部变换矩阵 → (pitch, yaw, roll) 度。不用 solvePnP。

    ⚠️ pitch 是第一行那个式子。`arctan2(-R[2,0], sy)` 是 **yaw** ——
    2026-09-23 写 `_scratch/_face_detect_rate.py` 时抄错过一次，
    量出来的"pitch"其实是左右转头。改这里之前先确认下标。
    """
    R = np.asarray(M, dtype=float)[:3, :3]
    sy = float(np.hypot(R[0, 0], R[1, 0]))
    return np.degrees([np.arctan2(R[2, 1], R[2, 2]),      # pitch
                       np.arctan2(-R[2, 0], sy),          # yaw
                       np.arctan2(R[1, 0], R[0, 0])])     # roll


# ── 时序工具（按时间戳，不按帧数）────────────────────────────────────
def norm_by_time(ts, vals, win, q=NORM_Q):
    """逐点用「它自己往前 win 秒」的 **q 分位** 做基线。按时间选窗，不按帧数。

    ── 为什么是分位数，且为什么是 75 而不是 50 ──────────────────────────
    基线要落在"睁眼"区间，所以分位数必须**高于闭眼占比**：
        p50 只撑到 50% 闭眼，p75 撑到 75%
    实测（2026-09-22 那场标了 11 次闭眼的会话，闭眼占了近一半时间）：
        p50 只检出 4/11 —— 基线被闭眼自己拽塌了，闭得越多越读不出来
        p75 检出 10/11，且离线 95 段的 phone 假闭眼几乎没变差
    这条对疲劳检测是要命的：真实疲劳就是高频闭眼，p50 是**自我抑制**的。

    也不用峰值跟踪（睁眼快跟上、闭眼慢下滑）：它对向上的噪声尖峰过敏，
    转头时 landmark 抖出的尖峰会把基线抬上去，离线 glance 段的假闭眼
    从 0.67 s 恶化到 1.6 s。分位数对双边的离群都钝，更稳。

    按时间选窗的原因：摄像头实际帧率随曝光漂移（这台实测 ~6~11 fps，名义 15）。
    按帧数算出来的「10 秒基线」实际是 15 秒，「30 秒窗」实际是 45 秒，
    眨眼频率还会被系统性低估 1.5 倍 —— 而且帧率每次录像都不一样，
    测一个固定值去补也没用。唯一稳的就是拿时间戳选。

    ⚠️ 因果性：基线的历史长度直接影响结果。离线是在**整段片段**上算的，
    实时若只喂 30 秒缓冲，窗口前 10 秒的基线就被截断了（历史不足）。
    实测同一段会话，"窗内基线"与"全历史基线"的单窗 PERCLOS 最大差 0.343。
    所以实时缓冲要留 HIST_SEC = WIN_SEC + ROLL_WIN = 27 秒：
    前 10 秒给基线热身，最后 WIN_SEC = 17 秒才拿去算统计。
    ⚠️ 这个 27 是**充要条件**不是余量 —— 统计窗里每个样本都要有自己的
    完整 10 秒基线史。（2026-09-23 把 WIN_SEC 从 30 改成 17，40 是旧值。）
    """
    ts, vals = np.asarray(ts, float), np.asarray(vals, float)
    out = np.empty(len(vals))
    j = 0
    for i in range(len(vals)):
        lo = ts[i] - win
        while ts[j] < lo:
            j += 1
        w = vals[j:i + 1]
        w = w[np.isfinite(w)]
        out[i] = np.percentile(w, q) if len(w) else np.nan
    return out


def runs_sec(ts, x, mask_fn):
    """满足 mask_fn 的连续段的**真实时长（秒）**。帧率会漂，除以 15 是错的。

    ⚠️ **时间戳有洞时这个时长会被撑大**：段的长度是 `ts[第一个不满足的帧] - ts[起点]`，
       所以两帧相隔 6.6 s 会被读成"连续 6.6 s"。实时路径的帧是均匀的（实测
       10 fps、段内最大间隔 0.11 s），但**缓存里的片段很稀疏**（glance_05 只有
       37 帧 / 25 s）—— 拿缓存标定时必须先看帧间隔，别把"5.33 s 的假哈欠"当成
       真样本。要修就得给这个函数加"相邻帧间隔超过多少就断段"，那会**同时动哈欠/
       闭眼/点头三条标定**，所以留在这儿当已知限制，不在这一次里悄悄改。
    """
    tsa = np.asarray(ts, float)
    out, cur, t0_ = [], False, 0.0
    for i, v in enumerate(x):
        if np.isfinite(v) and mask_fn(v):
            if not cur:
                cur, t0_ = True, tsa[i]
        elif cur:
            cur = False
            out.append(float(tsa[i] - t0_))
    if cur:
        out.append(float(tsa[-1] - t0_))
    return out


def yawn_plateau(ts, mar, win=YAWN_WIN):
    """MAR 的**滚动均值**（按时间选窗，不是按帧数）—— 判据挂在它上面，不挂在单帧上。

    ★ 为什么中间要垫一层均值：单帧 MAR 上哈欠和说话**完全重叠**
      （talking max 0.777 vs yawn_open p90 最低 0.727），唯一的分别是"张多久"，
      而说话/扭头会造成**贴着阈值的漂移**（glance_05 单帧在 0.50~0.57 徘徊了
      5.33 s）。单帧判据因此只能把阈值停在 0.60 上，再降就误报。
      均值把尖峰和漂移抹平：talking 侧从 0.87 s 塌到 0.13 s、glance 25 段全 0，
      而正例侧几乎不动（yawn_open 最短反而从 3.20 s 涨到 4.60 s）——
      两头都松了，这才是 YAWN_THR 敢降到 0.55、YAWN_MIN 敢降到 1.0 的原因。
      标定表见 YAWN_THR 的注释，脚本是 tools/calib_yawn.py 的【2c】。

    ⚠️ 窗内**有效帧少于 3 个**、或这一点本身是 NaN 的，给 NaN —— 和 EAR 那条
      一样，检不到脸就记成"没有张嘴"，偏保守（`runs_sec` 遇到 NaN 断段）。
    ⚠️ 这是**按样本平均**，不是按时间加权：实时路径 10 fps 均匀（实测
      `_probe_live_rules.py`：帧间隔中位 0.096 s），离线缓存里的片段不均匀
      （glance_05 只有 37 帧 / 25 s），所以这个量在**缓存上**只能做相对比较，
      不能当"平均张了多大"的物理量读。
    """
    ts, mar = np.asarray(ts, float), np.asarray(mar, float)
    out = np.full(len(mar), np.nan)
    j = 0
    for i in range(len(mar)):
        if not np.isfinite(mar[i]):
            continue
        lo = ts[i] - win
        while ts[j] < lo and j < i:            # 只看过去（因果），和 norm_by_time 同款
            j += 1
        w = mar[(ts >= lo) & (ts <= ts[i])]
        w = w[np.isfinite(w)]
        if len(w) >= 3:                        # noqa: PLR2004
            out[i] = float(np.mean(w))
    return out


def yawn_seconds(ts, mar):
    """这段里最长的一次"张嘴"持续了多少秒（0 表示没有）。

    ★ 判据 = 「**1.5 s 滚动均值** > YAWN_THR 连续多久」（见 yawn_plateau）。
      2026-09-26 之前比的是单帧 MAR —— 那一版在这里留了一段"返回值不稳"的
      ⚠️：一段 MAR 恰好贴着阈值徘徊的片段，两次运行会给出差别很大的数
      （yawn_open_03：离线 3.20 s、在线 5.53 s，而两趟 MAR 只差到第三位小数）。
      **换成滚动均值之后这一病根小多了但仍没消失**（均值也在阈值附近连续变化）——
      所以那条结论照旧：**判决稳、数字不稳，别把 yawn_sec 当测量值写进报告**，
      只写触发与否。

    ⚠️ 时长是按**时间戳**算的（`runs_sec`），而 `runs_sec` 会把时间戳间隔
      整段算进去：缓存里稀疏的片段（glance_05 只有 37 帧 / 25 s）能把两帧之间
      的 6.6 s 间隔读成"连续张嘴 5.33 s"。实时路径的帧是均匀的（10 fps），
      所以线上不会这样 —— 但**拿缓存做标定时必须知道这件事**。
    """
    return max(runs_sec(ts, yawn_plateau(ts, mar), lambda v: v > YAWN_THR) or [0.0])


def close_eye_seconds(ts, en):
    """这段里最长的一次"持续闭眼"有多少秒（0 表示没有）。

    `en` 必须是**已经归一化**的 EAR（`ear / norm_by_time(..., q=75)`）——
    归一化不在这里做，因为它的基线要在**全缓冲**上算（见 `window_features`），
    在切片里重算一遍就是"同一个窗两个口径"，正是本模块要消灭的那类静默降级。

    和 `yawn_seconds` 是同一个形状（判**持续**不判峰值），阈值见 `CLOSE_EYE_SEC`。
    ⚠️ 眨眼也会短促地压到 BLINK_THR 以下（0.1~0.4 s），所以这个量**必须**跟一个
      不短于 `CLOSE_EYE_SEC` 的门槛一起用；单独看它区分不了眨眼和闭眼。
    """
    return max(runs_sec(ts, en, lambda v: v < BLINK_THR) or [0.0])


def head_swing(ts, pitch, win=HEAD_WIN, ref_win=HEAD_REF_WIN):
    """最近 `win` 秒相对**平视位**下探了多少度 —— 带方向的低头量，单位度。

    判据 = `p95(最近 win 秒的 pitch) − 平视位`，平视位见 `head_ref`：

    ★ **有方向**（2026-09-26 用户第二问「我仰头为啥也算重度疲劳」）：
      仰头时返回的值 **≤ 0**，调用方那句 `>= HEAD_DEG` 永远不成立。
      旧版是无向的极差（p95 − p5），仰头和低头在它眼里一样（都是正 12°+）。
      ⚠️ 参考位（平视位）是**双侧修剪**出来的（第四次），它不会因为一次仰头就跑到
         抬头那一侧，所以仰头的**稳态**值明确是负的（实测合成 40 秒仰头 → −20.00）。
      ⚠️ **仰头刚开始的一两秒是个例外，值会落在 0 附近**：`hi`（最近 2 秒的 p95）
         还没跟上，而参考位还站在平视那一侧 —— 实测合成 14° 仰头 6 秒/11 秒、
         以及真人会话仰头段，最大值都是 **+0.00**（不是负数）。所以
         "仰头一定是负的"这句话不成立 —— 断言只该写 `< HEAD_DEG`。
    ★ 这条量的价值在于**几乎不需要基线**：参考位是"这个人的平视位"，历史不足时
      `head_ref` 只用现有的帧（它是**因果**的、只往前看），所以开机第 2 秒就有答案。
      而 `window_features` 里那个 `d_pitch` 要 `fb.ready()`（10 秒）才出数，
      而且窗是 17 秒、**拖尾**（半分钟前点过的头还在拉着它）。
    返回 NaN = 窗内有效帧太少（< 5）或参考位算不出来；别拿 NaN 去比大小。

    ⚠️ **可能返回负数**（短时仰头）。CSV 那一列 `head_swing` 会照原样写出负值 ——
       这是有意的：它让"仰头"在日志里看得见。判断触发一律写 `>= HEAD_DEG`，
       别写 `abs(...) >=`（那等于把方向又扔掉了，正是这次要修的 bug）。
    ⚠️ 持续低头要**超过 195 秒左右**（参考位的记忆，见 `HEAD_REF_WIN`）才会被认成
       "常态"、值回落 → 规则释放。**这个数 2026-09-26 一天之内从 7.5 秒 → 85 秒 →
       195 秒，每一步都是有意的**：低着 195 秒以上的头本来就该一直报。7.5 秒那个
       口径是**假触发**的根源（一次 11 秒的仰头就能把参考位拖走）；85 秒那个口径
       则挡不住**低头把参考位拖高**（实测低下去 13.0 秒就自己松手）。这是**行为
       改变**，不是漏报：那种姿态是"一直低着头"，支路一的体姿几何本来就在判它。
    ⚠️ 它只回答"头比平视位低了多大"，**分不出"低头困了"和"低头看仪表/
       扭头看镜子"**。阈值 10° 的实测代价见 `HEAD_DEG` 的注释
       （正常 0/27、扭头 1/25、疲劳 23/26）。
    """
    tsa = np.asarray(ts, float)
    p = np.asarray(pitch, float)
    if len(tsa) == 0:
        return float("nan")
    m = (tsa >= tsa[-1] - win) & np.isfinite(p)
    if m.sum() < 5:                                    # noqa: PLR2004
        return float("nan")
    hi = float(np.percentile(p[m], 95))
    # 参考位 = "现在的抬头位"（**窗末**那一点算出来的那个值，所以就是"现在的量比现在的
    # 抬头位低多少"，和 EAR 那条的写法完全对称）。
    # ⚠️ 取窗末（不是窗首）：窗首那个值会把"这次下探本身"排除在外，持续低头就永远
    #    算不成"下探"（`_calib_head_down.py` 的【6】两个口径都量了：窗末 → 正常
    #    0/27、疲劳 24/26；窗首 → 正常 2/27、疲劳 24/26）。
    ref = head_ref(tsa, p, ref_win=ref_win)
    if not np.isfinite(ref):
        return float("nan")
    return hi - float(ref)


def head_ref(ts, pitch, *, ref_win=HEAD_REF_WIN, q=HEAD_REF_Q):
    """当前这一刻的**平视位**（度，pitch 越小越抬头）。参考位永远是**最近这一刻**的值。

    = `最近 ref_win 秒里的双侧修剪分位`（见函数体那段 `★`）

    **2026-09-26 第四次之前换过两轮口径，两个旧实现都别回头捡**：
      · 「最近 `base_win`(10 s) 的 q 分位」与长窗项取 `max` —— **7.5 秒就松手**，
        那是 ① 假触发的真正根源，也是"低头 8 秒后自己判成没低"的根源。**已删**。
      · 「长史切段、各段各取 q 分位、取最高」—— 抗仰头、**不抗低头**（低头把最近
        那一段拖高，而 `max` 只采纳高的那一侧）→ 低下去 **13.0 秒**松手。**已删**。
    两次栽在同一个地方：**单侧规则只能防住一个方向**。现在的口径是双侧修剪
    （= 密度的众数）—— 参考位是"这个人的平视位"，仰头和低头**都是偏离**，
    "离当前估计超过 `HEAD_DEG` 度就不算数"这条**对两侧对称**。
    ⚠️ pitch **大 = 低头**（各组中位见 `HEAD_REF_Q`），所以这个"偏离"不是随意的
       阈值：它就是判据自己用的那个 10°，参考位和触发线是同一把尺子。

    ⚠️ **逐点函数，而且只认 `ts[-1]` 那一刻**（因果）：要算**历史某一刻**的参考位，
       就喂**那个时刻的前缀数组**（`ts[:j]`，`ts[j-1]` 是那一刻的最后一帧）——
       这正是"和在线同构"的用法，`_scratch/_check_head_dir.py` 的【1c】就是拿它
       跟记录值对账的。
    🔴 **签名是关键词专用的，这是有意的**：后面这几个窗口长度**没有** `now` 参数，
       因为我自己踩过——写成 `head_ref(ts, p, 60.0)` 想表达"t=60 那一刻"时，
       那个 60.0 被当成了窗口长度，**算出来的数完全不对而且不报错**
       （【1d】第一版整张表就这么废掉的）。位置参数被禁掉，这种误用会当场 TypeError。
       ⚠️ 2026-09-26 第四次把 `base_win`/`chunk` 从签名里**删掉**之后，
          `head_swing`/`HeadMotion.swing` 里那几处**位置参数**调用必须跟着改 ——
          `swing()` 原来是 `head_swing(B[:,0], B[:,1], self.win, self.base_win,
          self.ref_win, self.chunk)`，少一个形参之后那个 `base_win` 会**悄悄喂给
          `ref_win`**（10 s 当 300 s 用），数字全错、**一个字都不报**。已经改成
          关键字调用，别再写回位置的。
    ⚠️ 只用**有限**的 pitch 帧（没检到脸的那些不进分位，和 `norm_by_time` 一致）。
       返回 NaN = 有效帧少于 5。
    """
    tsa = np.asarray(ts, float)
    p = np.asarray(pitch, float)
    if len(tsa) == 0:
        return float("nan")
    now = float(tsa[-1])
    # 只在最近 ref_win 秒里找 —— 缓冲比 ref_win 长时不必每次扫全缓冲。
    i0 = int(np.searchsorted(tsa, now - ref_win, side="left"))
    v = p[i0:]
    v = v[np.isfinite(v)]          # 没检到脸的帧不进分位（和 `norm_by_time` 一致）
    if len(v) < 5:                 # noqa: PLR2004
        return float("nan")
    # ★ **双侧修剪**（2026-09-26 第四次）。以 `q` 分位为初值，反复丢掉离它超过
    #   `HEAD_DEG` 度的帧，再在剩下的**内点集**上重新取 `q` 分位。
    #   ⚠️ 迭代次数**由 `HEAD_REF_ITERS` 定（= 3）**，不用 while、也不按"变化够小就
    #     提前退"：这是个逐帧调用的函数，**离线和在线必须走同一条路径**（那种"看数据
    #     决定跑几轮"的写法会让同一份数据在两个场合给出不同的数，测试也就对不上了）。
    #   ⚠️ 内点少于 5 帧就**保留上一轮的 r 直接返回** —— `v[k]` 只有三四帧时再取
    #     分位没有意义，而且会跳。
    #   ⚠️ 初值 `q`(HEAD_REF_Q=35) 低、阈值是 10°：仰头/低头**谁先把估计拽走**取决于
    #     偏移占窗的比例（占比超过 1−q 才会被认成常态，见 `HEAD_REF_WIN` 的"记忆"）。
    #   ★ 为什么不是"单侧分位"或"分段取 max"：见 `HEAD_REF_WIN` 那段记录 ——
    #     仰头要往**高**的那一侧取、低头要往**低**的那一侧取，两个方向要**相反**的
    #     合并规则，**没有哪个顺序统计量能同时扛住**。修剪 = 密度的众数，对两侧对称。
    r = float(np.percentile(v, q))
    for _ in range(HEAD_REF_ITERS):
        k = np.abs(v - r) <= HEAD_DEG
        if int(k.sum()) < 5:       # noqa: PLR2004
            break
        r = float(np.percentile(v[k], q))
    return r


# ── 特征：离线与在线唯一的那份定义 ───────────────────────────────────
def _features(ts, ear, mar, pitch, en=None):
    """四个统计量。离线片段与实时窗口**都调这个**，不许另写。

    除数一律用**真实时长**。曾经的实时路径里 brate 除以真实窗长、
    而 yawns/nods 除以常量 WIN_SEC/60 —— 同一个窗里两种口径，
    今天看不出问题（哈欠列恒 0），但那是留了一个静默降级的雷。

    `en` 参数是给实时路径用的：`window_features` 已经在**全缓冲**上算好了
    归一化 EAR，必须传进来复用。不传的话这里会拿**当前这段 ts/ear** 重算一遍
    基线 —— 于是同一个窗里 `perclos` 走全缓冲、`brate` 走切片内，两个口径。
    这正是本模块要消灭的那类静默降级，所以留了个口子而不是让它自己重算。
    """
    ts = np.asarray(ts, float)
    dur = float(ts[-1] - ts[0])
    if dur < 5:
        return None
    if en is None:
        en = ear / np.maximum(norm_by_time(ts, ear, ROLL_WIN), 1e-6)
    pitch = np.asarray(pitch, float)
    mid = float(np.median(pitch[np.isfinite(pitch)])) if np.isfinite(pitch).any() else np.nan
    blinks = len(runs_sec(ts, en, lambda v: v < BLINK_THR))
    nods = len([d for d in runs_sec(ts, pitch, lambda v: abs(v - mid) > NOD_DROP)
                if d >= NOD_MIN])
    # 哈欠事件数：**必须和在线走同一个判据**（`yawn_plateau` + YAWN_THR/YAWN_MIN）。
    # 2026-09-26 判据换成滚动均值时这里也一起换了 —— 离线一个口径、线另一个口径，
    # 就是本模块开头警告的那类静默降级（当年 `brate` 除真实窗长、`yawns` 除常量
    # WIN_SEC/60 就是这么来的）。实测换完训练 96 段的 yawn 列仍是 0。
    _yp = yawn_plateau(ts, mar)
    yawns = len([d for d in runs_sec(ts, _yp, lambda v: v > YAWN_THR)
                 if d >= YAWN_MIN])
    return dict(perclos=float(np.mean(en < BLINK_THR)),
                brate=blinks / dur * 60.0,
                nod=nods / dur * 60.0,
                yawn=yawns / dur * 60.0,          # 哈欠**不入模型**（见 FEATURE_NAMES），
                                                  # 只为 tools/ablate_feats.py 的消融保留
                yawn_sec=yawn_seconds(ts, mar),
                dur=dur)


def clip_features(npz, key, need=FEATURE_NAMES):
    """从 `_ear_raw.npz` 里取一段片段的特征向量（离线：拟模型 / 消融用）。

    ⚠️ 返回 None 的两种原因要分清，别混成一句"样本不够"：
      · 字段缺失或长度不齐 —— 是**数据**问题（当前 106 段里有 10 段是这种）
      · 有效时长短于 5 秒 —— 是**片段**问题
    调用方（tools/fit_branch2.py）会把两者分别打出来，否则
    "用了 96 段"这个数字看起来像是随手丢的。
    """
    def g(f):
        k = f"{key}|{f}"
        return npz[k] if k in npz.files else None

    e, eu, ts, mar = g("ear"), g("euler"), g("t"), g("mar")
    if e is None or eu is None or ts is None or mar is None:
        return None, "缺字段"
    if not (len(eu) == len(e) == len(ts) == len(mar)):
        n = {len(e), len(eu), len(ts), len(mar)}
        return None, f"长度不齐 {sorted(n)}"
    m = np.isfinite(e) & np.isfinite(eu[:, 0])
    if not m.any():
        return None, "没有有效帧"
    f = _features(np.asarray(ts, float)[m], np.asarray(e, float)[m],
                  np.asarray(mar, float)[m], eu[m, 0])
    if f is None:
        return None, "有效时长 < 5 s"
    return [f[k] for k in need], None


def window_features(ts, ear, mar, pitch, win_sec=WIN_SEC):
    """实时路径的唯一入口：一段（HIST_SEC 长的）缓冲 → 统计量 + 诊断量。

    ★ 基线在**全缓冲**上算，统计只在**最后 win_sec 秒**做。
      这是 2026-09-23 修正的一处离在线口径差：早先直接把切片喂给
      `norm_by_time`，于是切片里前 10 秒的基线历史不足 —— 和离线
      "整段片段上算基线"不是同一个东西。缓冲留 HIST_SEC = WIN_SEC + ROLL_WIN
      秒就对齐了（现在是 27.0 = 17.0 + 10.0；这个和不是安全余量，是
      **充要条件**：窗口里每一个样本都要有自己的完整 10 秒基线历史）。

    返回 None = 还没热身（缓冲跨度不足 ROLL_WIN 秒）。
    调用方此时**必须**把支路二的票作废，不能拿 NaN 去喂模型。
    """
    ts = np.asarray(ts, float)
    if len(ts) < 3 or (ts[-1] - ts[0]) < ROLL_WIN:
        return None
    ear, mar = np.asarray(ear, float), np.asarray(mar, float)
    pitch = np.asarray(pitch, float)
    en = ear / np.maximum(norm_by_time(ts, ear, ROLL_WIN), 1e-6)
    s = ts >= ts[-1] - win_sec
    if s.sum() < 3:
        return None
    # ★ en[s] 必须传进去复用：不传的话 _features 会拿**这个切片**重算一遍基线，
    #   于是 perclos 走全缓冲、brate 走切片内 —— 同一个窗两个口径。
    st = _features(ts[s], ear[s], mar[s], pitch[s], en=en[s])
    if st is None:
        return None
    ps = pitch[s]
    d_pitch = (float(np.nanpercentile(ps, 95) - np.nanpercentile(ps, 5))
               if np.isfinite(ps).sum() > 10 else float("nan"))
    st.update(en_now=float(en[-1]), d_pitch=d_pitch, n_win=int(s.sum()),
              n_frames=int(s.sum()))
    return st



def feature_vector(stats, need=FEATURE_NAMES):
    """统计量 dict → 模型要的定长向量。顺序必须与 FEATURE_NAMES 一致。"""
    return [float(stats[k]) for k in need]


# ── 实时缓冲 ────────────────────────────────────────────────────────
class FaceBranch:
    """支路二的实时状态：(t, ear, mar, pitch) 缓冲 → 统计量。

    与 `_scratch/live_face.py:578-671` 的主循环同源。抽成类而不是继续散在主循环里，
    是因为那 741 行里最容易出错的**不是几何量，是缓冲与统计的时序** ——
    而时序错误不会崩，只会让数字慢慢偏，散在循环里没法单独测。

    ★ 四路必须装在**同一个 deque** 里。
      `live_face.py:622` 已经写过这条：分成三个 deque，某帧检不到脸就会错位，
      而闭眼的时候正好最容易丢帧 —— 错位了还看不出来，因为数值都还在合理范围内。
      也不按**帧数**裁剪：这台摄像头实测 6~11 fps 漂，按帧数裁出来的"40 秒缓冲"
      实际是 60~100 秒。只有按时间裁才保证缓冲真的是 hist_sec 秒。

    ★ 就绪分两级，不是一个布尔量。
        `ready()`  span >= ROLL_WIN   基线有历史了，够在屏上画 EAR_norm
        `full()`   span >= HIST_SEC   **窗口整个落在缓冲内**，这才敢喂模型
      差这一级的理由见 `window_features` 的 docstring：基线是全缓冲的 p75，
      而离线是在整段片段上算的。缓冲不满时窗口前段的基线历史被截断，
      和训练口径就不是同一个东西了 —— 正是模块开头说的那种"静默降级"。
      喂早了的代价不是报错，是概率整体偏低然后你以为模型不行。

    ★ 闸门关闭时**不要**再 `clear()` 了（2026-09-26 改；原来是"应该 clear"）。
      理由见 `clear()` 自己的 docstring —— 那条理由属于中位归一化时代，已被
      p75 滚动基线取代，而它的代价是**每次低头都把 27 秒热身清零**。
    """

    def __init__(self, hist_sec=HIST_SEC):
        self.hist_sec = float(hist_sec)
        self.buf = collections.deque()
        self.n = 0                      # 收到的帧数（含没检到脸的）

    def push(self, t, ear, mar, pitch):
        """塞一帧。**没检到脸时也要塞 NaN**，不要跳过。

        跳过的话 `perclos` 的分母就只剩"检到脸的帧"，等于把"看不见"从统计里
        抹掉了；塞 NaN 则 `norm_by_time` / `runs_sec` 会 mask 掉它，
        而 `en < BLINK_THR` 对 NaN 为 False —— 记成"没闭眼"，偏保守。
        `live_face.py:624` 就是这么做的，保持一致。
        """
        self.buf.append((float(t), float(ear), float(mar), float(pitch)))
        self.n += 1
        cut = float(t) - self.hist_sec
        # 至少留两点，否则 span 恒为 0、ready() 永假
        while len(self.buf) > 2 and self.buf[1][0] < cut:
            self.buf.popleft()

    def clear(self):
        """**融合回路里已经不再调它了**（2026-09-26）—— 留着只给离线探针脚本用。

        这里原来写着"闸门关闭时调用"，理由是"不清的话闸门一重开，缓冲里还是关闭
        期间那些被头姿污染的 EAR —— 30 秒的 PERCLOS 窗带着污染帧，重开瞬间就误报"。
        那条理由**属于中位归一化时代**（注释里那个"30 秒"也是 WIN_SEC=30 时的数），
        而 2026-09-23 换成 p75 滚动基线之后，头姿污染的消法变成了除法本身：
        低头时分子分母一起降，`ear/基线` 不动。实测（`_ear_raw.npz`）：

          · `phone`（低头看手机）18 段，归一化后最长"闭眼"中位 **0.20 s**、
            最长才 1.33 s —— 没有出现"低头被读成闭眼"那件事；
          · 这五组（含 phone/fatigue）的 EAR/MAR **有效率都是 100%** ——
            脸一直在被跟踪，眼睛一直被看见，从来不是"看不见所以不算"。

        反过来，留在回路里的代价是实打实的：**低头这个动作本身就会关上闸门**
        （支路一判非正常 → `gate` 假），于是支路二的缓冲、以及界面上那个
        "基线热身中 · 还需 N 秒"的倒计时，**每次低头都从零重攒**，
        一个经常低头的司机永远攒不满 27 秒 —— 越像疲劳的人越没有发言权。
        这与训练口径也不一致：训练集里 `phone`/`fatigue` 那 44 段**本来就是
        低着头拍完的**，`_features` 是在**整段**上算 perclos 的。
        """
        self.buf.clear()

    @property
    def span(self):
        return 0.0 if len(self.buf) < 2 else self.buf[-1][0] - self.buf[0][0]

    def ready(self):
        return self.span >= ROLL_WIN

    def full(self):
        return self.span >= self.hist_sec

    def warm_left(self):
        """还差多少秒才 full()。屏上照这个显示倒计时。"""
        return max(0.0, self.hist_sec - self.span)

    def arrays(self):
        B = np.array(self.buf, float)
        return B[:, 0], B[:, 1], B[:, 2], B[:, 3]

    def snapshot(self):
        """统计量 + 诊断量，缓冲不够就 None。**绝不要拿 NaN 去喂模型。**"""
        if len(self.buf) < 3:
            return None
        t, e, m, p = self.arrays()
        return window_features(t, e, m, p)


class HeadMotion:
    """头姿的**独立**缓冲 —— 专门喂 `head_swing`，与 `FaceBranch` 解耦。

    ⚠️ 为什么另起一条、不挂在 `fb` 上：这条规则的判据是"头低下去多少"，而
       **"头低下去"这件事本身就是闸门关闭的信号**（支路一判非正常 → `gate` 假）。
       挂上去等于让规则依赖一个会被自己触发的条件。所以只存 (t, pitch)，
       **永远不清零**，也不看闸门。

    ⚠️ 只存 pitch：`head_swing` 只用俯仰角。yaw 是"扭头"（glance 已从产品里
       删掉，不做了），存进来会让人以为这条规则也管左右看。

    ⚠️ 缓冲要留 `ref_win`(HEAD_REF_WIN=**300 秒**) —— 现在最长的那一项：
       参考位的双侧修剪要能回看到 300 秒前（见 `HEAD_REF_WIN`/`head_ref`）。
       只留 10 秒的话"平视位"会被任何一次持续偏移直接接管 —— 那就是一度出现过的
       "低着 8 秒就松手"的洞。
       留得长 **不代表要等这么久才能判** —— `head_ref` 只往前看，历史不足时
       它就用现有的帧（所以开机第 2 秒照样有答案）。这是它相对
       `window_features` 里的 `d_pitch` 唯一但决定性的好处（那个要 10 秒基线，
       而且窗是 17 秒、拖尾）。
       300 秒 × ~10 fps ≈ 3000 点，每帧 4 次 percentile，可以忽略。
    ⚠️ `base_win` **只管保留长度**（`push` 的 `cut`），判据里**已经没有这一项**了
       （2026-09-26 第四次，见 `head_ref` 函数体那段）。别以为传它进去能改判据 ——
       `head_swing` 的签名里已经把它删掉，传了也不会生效。
    """

    def __init__(self, win=HEAD_WIN, base_win=ROLL_WIN, ref_win=HEAD_REF_WIN):
        self.win = float(win)
        self.base_win = float(base_win)   # ⚠️ 只进 `cut`（保留长度），不进判据
        self.ref_win = float(ref_win)
        self.buf = collections.deque()
        self.buf = collections.deque()

    def push(self, t, pitch):
        """塞一帧。**没检到脸时也要塞 NaN** —— 理由同 `FaceBranch.push`：
        跳过会让"低了多少度"变成"能看见的那些帧低了多少度"，而看不见的时候
        正好可能是头低到极限的时候（判成"没动"是偏危险的那一侧）。
        """
        self.buf.append((float(t), float(pitch)))
        cut = float(t) - max(self.win, self.ref_win)
        while len(self.buf) > 2 and self.buf[0][0] < cut:
            self.buf.popleft()

    def swing(self):
        """最近 win 秒相对抬头位**下探**了多少度（**仰头时为负**）。
        NaN = 窗内有效帧不足 5 帧。

        ⚠️ 名字里的 `swing`（摆动，无向）是**旧判据**留下的。2026-09-26 起它返回的
           是带方向的下探量，名字没改是因为调用方在 `src/fuse.py`（**红线，不许动**）
           和 `ui/cam.py` 里 —— 改名会让红线文件当场报错。读这个数的时候记住：
           **只有正值（下探）才可能触发**，负值是仰头。
        """
        if len(self.buf) < 3:
            return float("nan")
        B = np.array(self.buf, float)
        # ⚠️ **关键字**调用：`head_swing` 的形参在 2026-09-26 第四次少了 `base_win`
        #    和 `chunk`，位置写法会让 `self.base_win`(10) 悄悄喂给 `ref_win`(300)，
        #    数字全错、一个字都不报。这个坑踩过一次，别再写回位置的。
        return head_swing(B[:, 0], B[:, 1], self.win, ref_win=self.ref_win)


