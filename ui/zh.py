"""繁简归一 —— **一处表，两个用处：匹配 和 显示**。

★ 2026-09-26 用户拍板「**全部是简体中文**」。在那之前这张表**只为匹配服务**
  （`ui/xiaorui.py` 的关键词表是简体的，whisper 吐繁体时一条都命中不了，
  所以先归一再比）。当时还专门写了一句「不要拿它去改写要说出口/要显示的话」
  —— 那条禁令**现在推翻**：用户看到屏幕上识别出来的自己那句话是繁体，问
  「我的话翻译出来为啥繁体字」。**主人说的话是机器生成的**，它和"小瑞的话术"
  不是一回事：话术是人手写的简体，本来就该原样念；识别结果是从模型嘴里出来的，
  不换就随模型的性子走。

⚠️ **谁是主路、谁是兜底，别搞反**：
  · **主路**是让模型自己别吐繁体 —— `ui/asr.py` 给 whisper 传的
    `SIMPLIFIED_PROMPT`（`initial_prompt`）。whisper 是多语种模型，简繁两套字形
    都在它的词表里，「普通话」这个语种**不区分简繁**，不给提示它就按训练语料里
    哪边多往哪边写，所以会飘。
  · **兜底**才是下面这张表：万一模型还是吐了繁体，在**识别器出口**换掉。
    表是不全的（手写的），可漏的字都长这样 —— 表里没有它，屏幕上就还是繁体。
    要彻底就得装 `opencc`；这台机器 `opencc`/`zhconv`/`pypinyin` **都没装**
    （实测 import 全 False），而为了一个字形映射去装依赖、改安装脚本、现场再
    联网，代价比"多写几行表"大得多。**所以这张表的正确理解是"够用"，不是"完整"。**

⚠️ 只收**繁体专用字形**（= 简体字形表里根本没有这个字）。像 `著`（著作）/
  `干`（干净）/ `发`/ `只`/ `丑`/ `松`/ `布` 这些**简体自己在用**的字一律**不收**：
  收了会把 `著作` 改成 `着作`、`干净` 改成 `干淨` 之类的东西，比不转更糟。
  同理 `帳` 也**故意不收** —— 它在简体里对应 `帐`（帐篷）和 `账`（账户）两个字形，
  一个字对两个目标，转错了看不出来。**一条规则：源字必须是"简体绝不会用的字形"，
  这样对已经正确的简体文本跑一遍就是恒等变换**（这一点由 `_scratch/_check_zh.py`
  对全部话术和页面文案断言，见那个文件）。

★ 2026-09-25 的现场证据（这张表最初就是为了它建的，留着）：
  `_scratch/_check_voice_do.py` 真量到过 —— 说「你好小瑞，给我放个音乐」，
  识别回来是「你好小瑞給我放客音樂」（`音樂` 是繁体，`个` 还错成了 `客`）。
  `音樂` 归一之后命中 `music`，才走到"做"那一步；`客` 是**听错字**、不是繁简，
  本文的表管不了那种，只能靠关键词别写太窄（`音乐` 在，所以照样命中）。
"""

from __future__ import annotations

# 繁體字形 -> 简体字形。按"什么时候会说到它"分组，方便后面补词时有地方加。
_T2S_PAIRS = (
    # —— 对话最常用的那批
    "給给 樂乐 個个 們们 聽听 說说 麼么 來来 誰谁 妳你 為为 於于 與与 從从 "
    "會会 應应 該该 幫帮 謝谢 嗎吗 這这 還还 沒没 讓让 見见 語语 話话 過过 "
    "問问 請请 對对 現现 時时 間间 裡里 裏里 邊边 頭头 後后 兒儿 點点 "
    # —— 车机 / 座舱
    "開开 關关 車车 導导 務务 區区 飛飞 機机 場场 廣广 麥麦 風风 調调 熱热 "
    "涼凉 溫温 鎖锁 險险 緊紧 勞劳 監监 測测 狀状 態态 報报 歷历 圖图 顯显 "
    "數数 據据 統统 計计 記记 錄录 設设 靈灵 項项 靜静 響响 範范 圍围 準准 "
    "標标 蓋盖 適适 隨随 續续 維维 護护 檢检 驗验 慣惯 頻频 節节 電电 單单 "
    "備备 視视 閉闭 駕驾 駛驶 轉转 彎弯 盤盘 剎刹 擋挡 檔档 離离 遠远 燈灯 "
    "鏡镜 輪轮 壓压 費费 國国 馬马 剛刚 經经 質质 議议 較较 讀读 寫写 聞闻 "
    "號号 兩两 幾几 長长 類类 嚴严 認认 誤误 頁页 觸触 總总 結结 紀纪 資资 "
    "業业 員员 級级 複复 雜杂 聲声 衛卫 發发 髮发 暫暂 繼继 碼码 濕湿 輕轻 "
    # —— 疲劳 / 生理（本项目的主场）
    "覺觉 睜睁 撐撑 暈晕 藥药 醫医 氣气 睏困 閉闭 "
)
_T2S = str.maketrans(dict(_T2S_PAIRS.split()))


def zh_t2s(text: str) -> str:
    """繁体字形 → 简体字形。**匹配和显示都用它**，见文首。

    对已经是简体的文本跑一遍**等于没跑**（表里只有繁体专用字形），所以可以放心
    在出口处无条件调用。**不做词替换**（`螢幕`→`屏幕`、`資訊`→`信息` 这类是词汇
    差异不是字形差异，本表不管，也不该管）。
    """
    return (text or "").translate(_T2S)
