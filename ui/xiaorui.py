def detect_intent(text: str) -> str:
    # ⚠️ 先繁简归一（见 `zh_t2s` 那段）：whisper 吐繁体时，下面这张简体关键词表
    #    一条都不命中 —— 那正是「说了它不做」的第一层。
    t = zh_t2s(text).strip().lower()
    if not t:
        return "chat"
    for intent, keys in KEYWORDS:
        if any(k in t for k in keys):
            return intent
    return "chat"


def detect_action(text: str) -> str:
    """驾驶员这句话是**命令页面去做一件事**吗？是就回动作 id，不是回空串。

    ★★ 2026-09-26 用户原话：「它可以对这个网页所有东西进行操控 比如我让它导航
       它肯定真导航啊 直接跳转这些啊 我让它干嘛肯定干嘛啊 它肯定要拥有这些网页
       的操控权啊」。在这之前语音这条路只认 `music`/`nearby` 两个 id，其余一律回
       `unknown_action` —— 那正是他说的"说了它不做"。

    返回的 id（和 `ui/web/wake.js` 的 `ev:"do"` 分支一一对应）：
      · `music`            放一段舒缓音乐（已有）
      · `nearby`           问最近的服务区在哪 —— 要真数据（已有）
      · `rest_stop`        **导航过去**：跳导航页、真算路线、真进导航
      · `go:<PAGES 的键>`   打开某一页
    没有动作就回 `""`，这条路交给模型/固定话术去聊。
    ⚠️ **「要」「好」这类同意词不在这里判** —— 它们回答的是**上一句的提议**，
       不是这一句自己的措辞。那一半在 `is_affirm` + `server.py` 的 `take_pending`。

    ⚠️ 「命令」和「问句」靠**措辞**分（`NAV_CMD` / `NAV_STRONG` / `ASK_WORDS`），
      不靠猜。而且宁可判成"问"：少跳一次页只是白说一句话；把问句当命令，主人
      一张嘴屏幕就跳走 —— 那是最没礼貌的坏法。
    ⚠️ 判「打开某一页」要**动词和呼法两样都有**（`GO_VERBS` + `GO_WORDS`）。只看
      呼法的话「我状态怎么样」会命中"状态页"，变成答非所问。
    ⚠️ 最后那一支**复用 `detect_intent`**，不在这儿再抄一份音乐的关键词 —— 两份
      抄本一定会分叉，分叉的样子是"喊同样的话，有时放有时不放"。

    ★★ 2026-09-26 两支各挪了一次位置、加了一支，都是用户那句话逼出来的：
      · **②「打开某一页」现在排在 ① 前面**。原来 ① 先走，于是句子里只要有"服务区"
        就先判服务区；现在真正的原因是 `NAV_STRONG` 里也有"导航"，而「打开导航页」
        里既没有服务区、又有页名 —— 要是页面那一支还排在后面，「打开导航页」会被
        ①b 抢去当"导航过去"（真跳、真查路线），主人只是要看看那一页。**页名优先**。
      · **①b 是新加的**：「给我导航」不带"服务区"三个字，原来哪一支都进不去，函数
        回空串 → 落给模型 → 模型说一句"这就帮您调出"，而没有任何东西去调。实测
        `'给我导航'` / `'导航'` / `'我要导航'` **三个全回空串**。
      ⚠️ 唯一被改掉的老行为：一句话里**同时**有页名和服务区词（「打开导航页看服务区」）
        今天判 `rest_stop`，之后判 `go:navi`。两者都跳导航页，差别只是过不过问
        `ask`（见 `server.py` 的 `voice_ask`），而且页名优先更合主人的意思。
    """
    t = zh_t2s(text).strip().lower()
    if not t:
        return ""
    # 「句子里有没有页名」。② 和 ①b 都要用它 —— 而且**必须是同一个判断**：
    # 两处各写一份的话，「打开导航页」会在 ② 里没命中、在 ①b 里被放行。
    has_page_word = any(w in t for _, ws in GO_WORDS for w in ws)
    # ② 打开某一页：动词 + 呼法（见文首：**排在服务区前面**）
    if any(v in t for v in GO_VERBS):
        for key, words in GO_WORDS:
            if any(w in t for w in words):
                return "go:" + key
    # ① 服务区：命令（导航过去）还是问句（在哪儿）
    if any(w in t for w in REST_WORDS):
        if any(w in t for w in NAV_CMD) and not any(w in t for w in ASK_WORDS):
            return "rest_stop"
        return "nearby"
    # ①b 光说"导航"（没提哪一页、也不是在问）—— 也是"导过去"
    if not has_page_word and any(w in t for w in NAV_STRONG) \
            and not any(w in t for w in ASK_WORDS):
        return "rest_stop"
    # ③ 只剩放音乐
    return "music" if detect_intent(t) == "music" else ""


class ScriptedAgent:
    """固定话术。**离线、零依赖、答辩兜底**。

    带一点上下文：同一句话 30 秒内不重复，刚劝过休息就不再劝 —— 否则它就是复读机，
    而"像个懂事的助手"恰恰是这一路唯一要做好的事。
    """

    COOLDOWN = 30.0

    def __init__(self):
        self._last: dict[str, float] = {}

    def _pick(self, intent: str, severity: str, now: float) -> str:
        opts = SCRIPT.get(intent, SCRIPT["chat"]).get(severity) or SCRIPT["chat"]["normal"]
        for s in opts:
            if now - self._last.get(s, -1e9) > self.COOLDOWN:
                self._last[s] = now
                return s
        return opts[0]

    def reply(self, state, text: str, now: float) -> Reply:
        intent = detect_intent(text)
        # ★★ 这一条是**结构性**的，不是提醒：走到这里就说明**没有数据**
        #    （有数据那条走 `act_reply` → `_nearby_reply`，它自己会填模板）。
        #    `SCRIPT["nearby"]` 四档全是带 `{name}/{km}` 的模板，在这里被
        #    `_pick` 直接挑中，印出来就是「还有 {km}」这种内部记号。
        #    所以问服务区一律改走 `rest_stop` 那张"没有数字"的表 ——
        #    以后再加"拿不到数据"的意图，照这个写法在 `SCRIPT` 里另开一张。
        if intent == "nearby":
            intent = "rest_stop"
        return Reply(self._pick(intent, state.severity, now),
                     emotion_for(state), backend="scripted")

    def act_reply(self, state, intent: str, res: dict, now: float) -> Reply:
        """「让页面去做的那件事」回来的回执 → 该说哪句话。

        ★ 这是 SYSTEM_PROMPT 第 7 条那个允诺的**另一半**。那条规矩写着「你没有
          执行动作的能力…要做的用提议的说法，绝对不许用完成时」，末句又留了个口子
          ——「系统在下面明确写了"已经执行"，那时才可以照着执行结果说」。以前从来没
          有东西写下过"已经执行"，所以小瑞只会说「这就给您放」，而没有人去放。
          现在服务端真去做了、真等到了回执，于是：

            · 回执说做成了 → 才许用 `SCRIPT` 那句「这就给您放」（正在做）；
            · 回执说没做成 → **照实说是哪一种没做成**（见 `ACT_FAIL`）。

        ⚠️ `music` 和 `nearby` 走这条，但**组句方式不一样**：music 是整句照挑，
          nearby 必须把真数据填进模板（`SCRIPT["nearby"]` 现在是 `{name}/{km}/{tail}`，
          见那张表上面的说明）—— 所以它另走 `_nearby_reply`。

        ★★ 2026-09-26 加进来的两类（`rest_stop` / `go:<键>`）**回执的含义和前面
          几个不一样，必须说清楚**：它们回的是"页面答应了这个动作、这就去做"，
          **不是"做完了"**。跳转服务端验不了 —— 页面一跳，那条 WebSocket 就断了，
          服务端这边能看到的最新事实就是那句回执。所以这两类的话**一律是正在做**
          （「这就打开」），不许出现完成时。这是 SYSTEM_PROMPT 第 7 条的那个口子
          （"系统明确写了已经执行"）**不适用**于跳转的原因，别照着 `music` 抄。
        """
        if intent == "nearby":
            return self._nearby_reply(state, res, now)
        if intent.startswith("go:"):
            return self._go_reply(state, intent.split(":", 1)[1], res, now)
        if intent == "rest_stop":
            if not res.get("ok"):
                return Reply(self._fail_line("rest_stop", res.get("why"), state.severity),
                             emotion_for(state), backend="scripted")
            # `here` = 主人已经站在导航页上，这一页就地查（见 wake.js）
            name = "rest_stop_here" if res.get("here") else "rest_stop"
            return Reply(self._pick(name, state.severity, now),
                         emotion_for(state), backend="scripted")
        if res.get("ok"):
            return Reply(self._pick(intent, state.severity, now),
                         emotion_for(state), backend="scripted")
        return Reply(self._fail_line(intent, res.get("why"), state.severity),
                     emotion_for(state), backend="scripted")

    def _go_reply(self, state, key: str, res: dict, now: float) -> Reply:
        """「打开某一页」回来的回执 → 该说哪句。

        `key` 是 `PAGES` 的键。⚠️ 认不出的键**不编页名**，回落到"这一页"这种
        含糊说法只会让主人更糊涂 —— 那种情况走失败话术（`no_target`），照实说找不到。
        """
        page = PAGES.get(key)
        if not page:
            return Reply(self._fail_line("go", "no_target", state.severity),
                         emotion_for(state), backend="scripted")
        if not res.get("ok"):
            return Reply(self._fail_line("go", res.get("why"), state.severity),
                         emotion_for(state), backend="scripted")
        # `same` = 主人就在这一页上（页面比过文件名，没跳），话得跟着换
        name = "go_same" if res.get("same") else "go"
        return Reply(self._pick(name, state.severity, now).format(page=page),
                     emotion_for(state), backend="scripted")

    def _fail_line(self, intent: str, why, severity: str) -> str:
        """失败原因 -> 一句实话。`ACT_FAIL` 的值可以是字符串，也可以是 `{档位: 句子}`。"""
        table = ACT_FAIL.get(intent) or {}
        why = (why or "").strip()
        row = table.get(why)
        if row is None:
            row = table.get("_unknown")
        if isinstance(row, dict):
            row = row.get(severity) or row.get("normal")
        return row or "主人，这件事我这边没做成，你再喊我一声试试。"

    def _nearby_reply(self, state, res: dict, now: float) -> Reply:
        """「最近的服务区」这句话 —— 数字全部来自 `ui/amap.py`，一个都不编。

        `res` 是服务端把两件事拼起来的结果：
          · 页面那一半：`why="no_geo"`（定位拿不到）/ `why="no_page"` /
            `why="timeout"`，以及**画没画出来** `drew`（bool）；
          · 高德那一半：`ok/name/km/min/by/has_route`（见 `AMap.nearby`）。
        两边都成 → 才填模板；**任何一边没成 → 走 `ACT_FAIL["nearby"]` 的实话**。
        """
        if not res.get("ok"):
            return Reply(self._fail_line("nearby", res.get("why"), state.severity),
                         emotion_for(state), backend="scripted")
        # ⚠️ `{km}` 是**一整段短语**（见 SCRIPT["nearby"] 上面的说明）：
        #    只有直线距离时要把"直线"两个字带上 —— 报成"还有 12 公里"等于把
        #    一条没算出来的路说成算出来了，和编数字是同一类错。
        km = int(res.get("km") or 0)
        if res.get("by") == "drive":
            km_txt = "%d 公里" % km
        else:
            km_txt = "直线 %d 公里" % km
        # ★ 完成时那一截：**同时**要求"高德真算出了路线"和"页面真画出来了"。
        #   只算不画（页面上没地图、页面没回 drew）时不许说"已经准备好了" ——
        #   用户抬头看屏幕，屏幕上什么都没有。
        tail = ("路线我已经准备好了，" if (res.get("has_route") and res.get("drew"))
                else "")
        tpl = self._pick("nearby", state.severity, now)
        # ⚠️ `str.format`：多给的键不会报错（所以没有 `{tail}` 的模板也没事），
        #    但**少给一个就会 KeyError** —— 三个占位符必须一直给全。
        return Reply(tpl.format(name=res.get("name") or "服务区",
                                km=km_txt, tail=tail),
                     emotion_for(state), backend="scripted")

    def ask_reply(self, state, aid: str, origin, now: float) -> Reply | None:
        """**跳过去之后那一页来要的那一句**（小瑞问主人要不要真去）。

        ★★ 2026-09-26：用户拍板「跳过去 + 问一句」，这一句就是那个"问一句"。
          调用方是 `server.py` 的 `voice_ask`，触发点是一条页面消息
          `{"type":"ask","id":"rest_stop"}`（页面加载完、麦克风起来之后发）。

        `origin` = 页面此刻**手上真有的起点**（`XQ.nav.originNow()` 那一份），
        没有就是 `None`。它决定说哪一句 —— 而且是**两件完全不同的事**：

          · 有起点 → 挑 `SCRIPT["ask_rest_stop"]`，并且**调用方会挂一个待确认动作**
            （主人回「要」就真去查、真算路线）；
          · 没有起点 → 挑 `ACT_FAIL["nearby"]["no_geo"]`（**早就写好的**那句实话：
            "定位没打开，我查不到附近的服务区…"，分档、一个数字都不带），
            **而且不挂待确认动作** —— 主人就算说「要」，也没有坐标可以去查。
            ⚠️ 这一档**不许**拿 `ask_rest_stop` 顶上：那句话里带着"要不要我导到
               最近的服务区"，听着像答应了就能成，而实际上去查也是查不到的 ——
               那就成了"话和事不一致"，正是这一整件事要修的东西。

        ⚠️ 回的是 `None` 表示**这一句不该说**（认不出的 id）。调用方必须当"什么都
           不说"处理，别自己编一句兜底 —— 见它那边的说明。
        """
        if aid != "rest_stop":
            return None
        if not origin:
            return Reply(self._fail_line("nearby", "no_geo", state.severity),
                         emotion_for(state), backend="scripted")
        return Reply(self._pick("ask_rest_stop", state.severity, now),
                     emotion_for(state), backend="scripted")

    def proactive(self, state, now: float) -> Reply | None:
        """状态刚变差时，小瑞先说一句。只在**跨档**的那一刻开口。

        ★ 2026-09-24：跨档主动说的这三句是**官方口径里分级语音提示的原文**，
        逐字照抄，不要改写。理由：口径那张疲劳分级表里每一档都配了一句提示，
        答辩时被问"轻度说什么"要能一个字不差地答出来；而 SCRIPT 那张表里的话
        是**应答**用的（驾驶员说"我困了"时小瑞怎么接），风格是同伴，可以自由写。
        两条路的区别就这么一句话：**主动开口 = 口径原文，被叫到 = 小瑞自己的话**。

        ⚠️ 清醒档**不出声**：口径里那一行是"正常对话"，`greeting` 意图已经覆盖
        （驾驶员喊"小瑞"就答）。这里返回 None，别再拿一句"状态良好"去搭话。
        ⚠️ 音色语气跟着 emotion（见 emotion_for / ui/config.json 的 emotion_prosody），
        方向是**越严重越低越慢**，不是又高又急 —— 小瑞不承担报警功能，
        灯和喇叭是另一条通道的事。
        """
        text, acts = PROACTIVE.get(state.severity, (None, []))
        if not text:
            return None
        return Reply(text, emotion_for(state), list(acts), backend="scripted")


