SYSTEM_PROMPT = """你是「小瑞」，智能座舱里的虚拟助手，坐在副驾上的同伴。
性格乖巧温柔、懂事体贴，语气亲昵但不油腻。**每一次回复都必须称呼驾驶员为「主人」**
（硬性要求，不许省略、不许换成"您"或"你"——用户原话：「我只喊主人呀，换不了口」）。
你的声音是柔和的，所以话要像说出来的，不像写出来的。

你的运行环境是车载 DMS 疲劳监测系统：后台每一拍都会把驾驶员的疲劳状态写在下面那行
【当前状态】里。**你的回答必须结合它，不能无视驾驶状态随便闲聊。**

规矩（必须遵守）：
1. 说话简短：**40~60 字、一到两句**，车内不适合长文本。不要分点、不要小标题，
   不要用 emoji。
2. 按【当前状态】那一档说话：
   · 清醒 —— 可以轻松闲聊、回答问题，主动简单聊两句路况。
   · 轻度疲劳 L1 —— 温柔地提醒休息，语气关切（例如：「主人，稍微打起精神哦，
     可以开窗透透气。」）。
   · 中度疲劳 L2 / 重度疲劳 L3 —— 语气变认真，明确建议休整；主人还没拒绝过的话，
     主动问他是不是要找最近的服务区。
3. **绝对不许编造数据**。所有数据只能用下面【当前状态】里给出的值，没给出的就
   说没量到。心率尤其如此：**只有【当前状态】里写了「心率=」你才能说数字**，
   那一行没有就是此刻真的没量到（手指没按上去、或者设备没接），被问到就如实说
   还没量到，不要猜、也不要说"没有这个功能"——这个功能是有的。
4. 不要重复上一句劝休息的话。主人已经明确拒绝一次，就换个方式或先顺着他说。
5. **你不承担报警功能** —— 灯光和语音那一套负责安全告警，你是同伴不是警报器。
   所以哪怕疲劳严重，也不要用感叹号和命令句、不要长篇教育；只把语气放认真，
   给一个具体动作（导服务区、放音乐）。
6. 回答中文。不要提"我作为 AI"这类话。

可用的动作（可以提，但**只能"提议"，不能声称已经做了**）：
播放舒缓音乐 / 导航至最近服务区 / 查看驾驶状态 / 附近有服务区吗

7. 🔴 **你没有执行动作的能力，只有"提议"的能力。** 上面那几件事由座舱界面
   去做，不是你说一句就发生。所以：
   · 想去做的，用"要不要我…？""我帮你…？"这种**提议**的说法；
   · **绝对不许用完成时**说这些事 ——「已经放上了」「音量帮您调小了」「已经帮您
     导好了」全是**谎话**，屏幕上一动没动，主人一眼就能看穿；
   · 主人让你放歌、放音乐时，你可以说"这就给您放"（正在做）或"我这边放一段
     舒缓的，好不好？"（提议），**但不能说"已经放好了"**；
   · 唯一例外：系统在下面明确写了"已经执行"，那时才可以照着执行结果说。
"""


def state_brief(state) -> str:
    """把状态压成一行给模型看。**只给真实存在的量**，没有的就不写。"""
    bits = [f"疲劳程度={state.severity_name}", f"安全级别=L{state.level}（{state.level_name}）",
            f"注意力={state.attention}"]
    if state.perclos is not None:
        bits.append(f"PERCLOS={state.perclos*100:.1f}%")
    if state.p_fat is not None:
        bits.append(f"疲劳概率={state.p_fat:.2f}")
    if state.brate is not None:
        bits.append(f"眨眼频率={state.brate:.0f}次/分")
    if state.pitch is not None:
        bits.append(f"头部俯仰={state.pitch:.0f}°")
    if state.nod is not None:
        bits.append(f"点头次数={state.nod:.0f}")
    # 「刚刚打过哈欠」**不在这里另拍阈值**：读 `derive()` 已经判好的那条告警
    # （`ui/state.py:298`，按 config 的 `alarm.yawn_min` 判）。原来这里硬编码
    # `>= 2.0`，是同一个数的**第五份抄本** —— 2026-09-26 把 YAWN_MIN 从 2.0
    # 改成 1.2 时差点漏掉它，漏掉的样子是「横幅报打哈欠了，小瑞那边还说没睡够」，
    # 同一屏上两个判据各判各的。⚠️ 前提：`alarms` 由 `derive()` 填，服务端每次
    # 拿到状态都先 derive（`ui/server.py:563`），所以这里读得到。
    if any(a.get("kind") == "yawn" for a in (state.alarms or [])):
        bits.append("刚刚打过哈欠")
    # ★ 2026-09-26：心率接上了（HPM5300 + MAX30102 从串口进来，见 ui/serial_hr.py），
    # 所以这一句从**无条件写"未接入"**改成和上面几路同一个写法：有才写。
    # ⚠️ 原来那一版是这份函数里唯一一处"没有也写"的 —— 后果不只是多一句话：
    #   模型每次都被明确告知"心率没接入"，于是主人问心跳多少时它会照直说没接入，
    #   哪怕这一刻屏幕上正显示着一个真数（同一个屏两套话）。
    # ⚠️ 没有的时候**什么都不写**（而不是写"心率未接入"），因为人设第 3 条
    #   现在的口径是「那一行没有 = 此刻没量到」，写出来反而会让模型去解释原因。
    if state.hr is not None:
        bits.append(f"心率={state.hr:.0f}次/分")
    return "【当前状态】" + "；".join(bits)


class Agent:
    """对外的唯一入口。backend = auto / deepseek / scripted。"""

    def __init__(self, cfg: dict, scripted: ScriptedAgent | None = None):
        ag = (cfg.get("agent") or {})
        self.mode = (ag.get("backend") or "auto").lower()
        d = ag.get("deepseek") or {}
        key, self.key_src = resolve_key(d)
        self.client = DeepSeekClient(d.get("base_url", "https://api.deepseek.com"),
                                     d.get("model", "deepseek-flash"), key,
                                     d.get("timeout_s", 12.0),
                                     d.get("temperature", 1.0),
                                     d.get("max_tokens", 220))
        self.scripted = scripted or ScriptedAgent()
        self.last_error = ""

    @property
    def api_on(self) -> bool:
        return self.mode in ("auto", "deepseek") and self.client.ready

    def _via_api(self, state, text: str, history: list[dict]) -> Reply:
        msgs = [{"role": "system", "content": SYSTEM_PROMPT},
                {"role": "system", "content": state_brief(state)}]
        # ★ 2026-09-24 晚：这里曾经做成「正常那一档不注入【当前状态】」，因为
        #   怀疑每拍硬塞一行车况会把闲聊全拽回开车。**当晚按用户给的人设第 5 条
        #   又改回每拍都注入了** —— 人设明写「优先参考系统下发过来的驾驶员疲劳状态，
        #   你的回答需要结合该状态，**不能无视驾驶状态随便闲聊**」，而清醒那一档
        #   还要求"主动简单聊两句路况"，那它就必须知道现在是不是清醒。
        #   于是：三档都注入。真正治"像固定话术"的是**规矩 1 的长度**（40 字那句
        #   已经删掉），不是这一行 —— 别再把它做成条件注入。
        for h in history[-6:]:                      # 只带最近几轮，省 token
            if h.get("role") in ("user", "assistant") and h.get("content"):
                msgs.append({"role": h["role"], "content": h["content"]})
        msgs.append({"role": "user", "content": text})
        out = self.client.chat(msgs)
        if not out:
            raise RuntimeError("回复是空的")
        return Reply(out, emotion_for(state), backend="deepseek")

    def respond(self, state, text: str, history=None, now=None) -> Reply:
        """驾驶员说话 -> 小瑞的回复。**任何失败都退回固定话术**，不会开天窗。"""
        now = time.monotonic() if now is None else now
        history = history or []
        if self.mode == "scripted" or not self.client.ready:
            if self.mode == "deepseek" and not self.client.ready:
                self.last_error = "配了 deepseek 但没有 key，已退回固定话术"
            return self.scripted.reply(state, text, now)
        try:
            return self._via_api(state, text, history)
        except Exception as e:
            # 现场断网、限流、模型名过期……都走这里。界面会显示"本地话术"，
            # 让看的人知道现在不是模型在答 —— 这是诚实，也是答辩的加分点。
            self.last_error = str(e)
            r = self.scripted.reply(state, text, now)
            r.backend = "scripted(API失败)"
            return r
