class Reply:
    def __init__(self, text: str, emotion: str, actions=None, backend="scripted"):
        self.text = text
        self.emotion = emotion
        self.actions = actions or []
        self.backend = backend

    def to_json(self) -> dict:
        # ★ 2026-09-26：**出去的每一句话都从这里过**（三条路都是 `r.to_json()` ——
        #   固定话术、模型、动作确认），所以繁简归一放在这儿一处就够，见
        #   `ui/zh.py`。为什么连回复也要转：用户拍板的是「**全部**是简体中文」，
        #   而模型的输出**不受我们控制** —— 系统提示词是简体、它一般也就答简体，
        #   但那是它的自由，不是我们的保证。这张表对简体是**恒等变换**（源字全是
        #   繁体专用字形），所以留着它只可能做一件事：万一模型吐了繁体，屏幕上
        #   和嘴里都不是繁体。**话术一个字也改不动**（本来就是手写的简体）。
        return {"text": zh_t2s(self.text), "emotion": self.emotion,
                "actions": self.actions, "backend": self.backend}


def emotion_for(state) -> str:
    """表情 = 疲劳程度（情感通道）；但**安全通道更急时以安全为准**。

    比如支路一判到 L3（紧急）而支路二还没热身完，小瑞不能还笑着。
    这就是"两级权限"在代码里的样子：取两者里更严肃的那个。
    """
